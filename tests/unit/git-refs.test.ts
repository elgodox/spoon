test('branches: create, checkout, rename, list current/upstream, delete', async () => {
  const repo = makeRepo()
  await git.createBranch(repo, 'feature/x', true)
  assert.equal((await git.getStatus(repo)).branch, 'feature/x')
  await git.createBranch(repo, 'parked', false)
  assert.equal((await git.getStatus(repo)).branch, 'feature/x')
  await git.checkout(repo, 'main')
  await git.renameBranch(repo, 'parked', 'renamed')
  let names = (await git.getBranches(repo)).map((b) => b.name).sort()
  assert.deepEqual(names, ['feature/x', 'main', 'renamed'])
  assert.equal((await git.getBranches(repo)).find((b) => b.current)?.name, 'main')
  await git.checkout(repo, 'new-one', true)
  assert.equal((await git.getStatus(repo)).branch, 'new-one')
  await git.checkout(repo, 'main')
  write(repo, 'only-on-x.txt', 'x')
  await git.checkout(repo, 'feature/x')
  commitAll(repo, 'unmerged work')
  await git.checkout(repo, 'main')
  await assert.rejects(git.deleteBranch(repo, 'feature/x', false), /not fully merged/)
  await git.deleteBranch(repo, 'feature/x', true)
  await git.deleteBranch(repo, 'renamed')
  names = (await git.getBranches(repo)).map((b) => b.name).sort()
  assert.deepEqual(names, ['main', 'new-one'])
  const startPoint = head(repo, 'HEAD~0')
  await git.createBranch(repo, 'from-start', false, startPoint)
  assert.equal(head(repo, 'from-start'), startPoint)
})

test('tags: lightweight, annotated, on a specific commit, delete', async () => {
  const repo = makeRepo()
  const first = head(repo)
  write(repo, 'b.txt', 'b')
  commitAll(repo, 'second')
  await git.createTag(repo, 'light')
  await git.createTag(repo, 'v1.0', 'Release 1.0')
  await git.createTag(repo, 'old', undefined, first)
  const tags = await git.getTags(repo)
  const by = Object.fromEntries(tags.map((t) => [t.name, t]))
  assert.equal(by['v1.0'].message, 'Release 1.0')
  assert.equal(head(repo, 'old'), first)
  assert.equal(sh(repo, ['cat-file', '-t', 'v1.0']).trim(), 'tag')
  await git.deleteTag(repo, 'light')
  assert.deepEqual((await git.getTags(repo)).map((t) => t.name).sort(), ['old', 'v1.0'])
})

