test('stash: push (incl. untracked), list, apply, pop, drop, partial paths', async () => {
  const repo = makeRepo('stash', { 'a.txt': 'a\n', 'b.txt': 'b\n' })
  assert.deepEqual(await git.getStashes(repo), [])
  write(repo, 'a.txt', 'a2\n')
  write(repo, 'new.txt', 'n\n')
  await git.stashPush(repo, 'wip one')
  assert.equal((await git.getStatus(repo)).unstagedCount, 0)
  let stashes = await git.getStashes(repo)
  assert.equal(stashes.length, 1)
  assert.equal(stashes[0].selector, 'stash@{0}')
  assert.match(stashes[0].message, /wip one/)
  const applied = await git.stashApply(repo, 'stash@{0}', false)
  assert.equal(applied.code, 0)
  assert.equal(existsSync(join(repo, 'new.txt')), true)
  assert.equal((await git.getStashes(repo)).length, 1)
  await git.discard(repo, ['a.txt', 'new.txt'])
  await git.stashApply(repo, 'stash@{0}', true)
  assert.equal((await git.getStashes(repo)).length, 0)
  await git.stashPush(repo, 'only a', ['a.txt'])
  const st = await git.getStatus(repo)
  assert.deepEqual(st.unstaged.map((e) => e.path), ['new.txt'])
  stashes = await git.getStashes(repo)
  await git.stashDrop(repo, stashes[0].selector)
  assert.deepEqual(await git.getStashes(repo), [])
})

