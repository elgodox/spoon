function conflictRepo() {
  const repo = makeRepo('conflict', { 'shared.txt': 'base\n' })
  sh(repo, ['checkout', '-q', '-b', 'other'])
  write(repo, 'shared.txt', 'theirs\n')
  commitAll(repo, 'other side')
  sh(repo, ['checkout', '-q', 'main'])
  write(repo, 'shared.txt', 'ours\n')
  commitAll(repo, 'main side')
  return repo
}

test('merge conflict: readConflict, writeResolved, continueMerge', async () => {
  const repo = conflictRepo()
  const r = await git.mergeBranch(repo, 'other')
  assert.notEqual(r.code, 0)
  const conflict = await git.readConflict(repo, 'shared.txt')
  assert.equal(conflict.base, 'base\n')
  assert.equal(conflict.ours, 'ours\n')
  assert.equal(conflict.theirs, 'theirs\n')
  assert.match(conflict.working, /<<<<<<<[\s\S]*=======[\s\S]*>>>>>>>/)
  await git.writeResolved(repo, 'shared.txt', 'ours\ntheirs\n')
  const done = await git.continueMerge(repo)
  assert.equal(done.code, 0)
  assert.equal((await git.getStatus(repo)).merging, false)
  assert.equal(readFileSync(join(repo, 'shared.txt'), 'utf8'), 'ours\ntheirs\n')
})

test('merge conflict: abortMerge restores the branch', async () => {
  const repo = conflictRepo()
  const before = head(repo)
  await git.mergeBranch(repo, 'other')
  await git.abortMerge(repo)
  const st = await git.getStatus(repo)
  assert.equal(st.merging, false)
  assert.equal(head(repo), before)
})

test('rebase: clean rebase, conflict + continue, conflict + abort', async () => {
  const repo = makeRepo('rebase', { 'base.txt': 'b\n' })
  sh(repo, ['checkout', '-q', '-b', 'topic'])
  write(repo, 'topic.txt', 't\n')
  commitAll(repo, 'topic')
  sh(repo, ['checkout', '-q', 'main'])
  write(repo, 'main.txt', 'm\n')
  commitAll(repo, 'main moved')
  sh(repo, ['checkout', '-q', 'topic'])
  const clean = await git.rebaseOnto(repo, 'main')
  assert.equal(clean.code, 0)
  assert.deepEqual(log(repo), ['topic', 'main moved', 'Initial commit'])

  const c = conflictRepo()
  sh(c, ['checkout', '-q', 'other'])
  const failed = await git.rebaseOnto(c, 'main')
  assert.notEqual(failed.code, 0)
  assert.equal((await git.getStatus(c)).rebasing, true)
  await git.rebaseAbort(c)
  assert.equal((await git.getStatus(c)).rebasing, false)

  await git.rebaseOnto(c, 'main')
  await git.writeResolved(c, 'shared.txt', 'merged\n')
  const cont = await git.rebaseContinue(c)
  assert.equal(cont.code, 0)
  assert.equal((await git.getStatus(c)).rebasing, false)
  assert.deepEqual(log(c), ['other side', 'main side', 'Initial commit'])
})

