test('getCommits returns subjects, bodies, parents, refs and a graph layout', async () => {
  const repo = makeRepo()
  write(repo, 'a.txt', 'a')
  sh(repo, ['add', '-A'])
  sh(repo, ['commit', '-q', '-m', 'feat: add a', '-m', 'Body line'])
  sh(repo, ['tag', 'v1'])
  sh(repo, ['branch', 'side'])
  const commits = await git.getCommits(repo, 10, ['--all'])
  assert.equal(commits.length, 2)
  const top = commits[0]
  assert.equal(top.subject, 'feat: add a')
  assert.equal(top.body, 'Body line')
  assert.equal(top.parents.length, 1)
  assert.equal(top.shortHash, top.hash.slice(0, 7))
  assert.equal(top.email, 'spoon-test@example.com')
  const refs = top.refs.map((r) => `${r.type}:${r.name}`)
  assert.ok(refs.includes('head:main'))
  assert.ok(refs.includes('local:side'))
  assert.ok(refs.includes('tag:v1'))
  assert.equal(commits[1].parents.length, 0)
  assert.equal(typeof top.lane, 'number')
  assert.equal((await git.getCommits(repo, 1)).length, 1)
})

