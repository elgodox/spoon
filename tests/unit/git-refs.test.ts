test('fileTree builds a sorted folder tree and showFile reads blobs', async () => {
  const repo = makeRepo('tree', { 'b.txt': 'b', 'src/z.ts': 'z', 'src/a/x.ts': 'x', 'a.txt': 'a' })
  const tree = await git.fileTree(repo)
  assert.deepEqual(tree.map((n) => `${n.type}:${n.name}`), ['dir:src', 'file:a.txt', 'file:b.txt'])
  const src = tree[0]
  assert.deepEqual(src.children!.map((n) => n.path), ['src/a', 'src/z.ts'])
  assert.deepEqual(src.children![0].children!.map((n) => n.path), ['src/a/x.ts'])
  assert.equal((await git.showFile(repo, 'HEAD', 'src/z.ts')).toString(), 'z')
  assert.equal((await git.showFile(repo, 'HEAD', 'nope.txt')).length, 0)
  assert.deepEqual(await git.fileTree(repo, 'not-a-rev'), [])
})

